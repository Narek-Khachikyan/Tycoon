/**
 * Числа раскладки — единственный источник ширин колонок и порога одноколоночного режима.
 *
 * Базис колонок не зависит от содержимого активной вкладки магазина. Раньше ширина правой
 * колонки задавалась `min`/`max` по содержимому, и переход «Модели» → «Апгрейды» сужал её
 * примерно на 18%, а центральная колонка вбирала освободившееся место: разделители съезжали,
 * и взгляд, который читает экран каждые несколько секунд, терял ориентир.
 *
 * Порог трёхколоночного режима равен сумме минимумов колонок, а не задан отдельно: между
 * колонками нет ни зазоров, ни отступов, поэтому лишних слагаемых не требуется, а разойтись
 * раскладка и порог уже не могут.
 *
 * Модуль отвечает и за второй вопрос того же рода — сколько места по вертикали. Ширины и
 * пороги приезжают в CSS отсюда (`--col-click`, `--col-shop`), и высоты полос оболочки
 * приезжают оттуда же, потому что обе задачи решает одно число на один вопрос.
 */

/** Минимум колонки Клика, px. */
export const CLICK_COL_MIN = 300;
/** Максимум колонки Клика, px — прежний предел, до которого колонка и доли окна. */
export const CLICK_COL_MAX = 380;
/** Доля окна, на которой колонка Клика доходит до максимума. */
export const CLICK_COL_SHARE = 0.27;

/** Минимум колонки магазина, px. */
export const SHOP_COL_MIN = 340;
/** Максимум колонки магазина, px. */
export const SHOP_COL_MAX = 440;
/** Доля окна, на которой колонка магазина доходит до максимума. */
export const SHOP_COL_SHARE = 0.31;

/**
 * Минимум колонки офиса, px. Офис — единственная растягиваемая колонка, поэтому её минимум
 * задаёт нижнюю границу окна, на которой три колонки ещё помещаются.
 */
export const OFFICE_COL_MIN = 360;

/** Ширина окна, ниже которой три колонки перестают помещаться и игра переходит в одну. */
export const THREE_COL_MIN = CLICK_COL_MIN + SHOP_COL_MIN + OFFICE_COL_MIN;

/**
 * Ширина окна, ниже которой шапка сжимается до одного ряда: на 390 px она занимала две
 * строки, а подвал с атрибуцией Artificial Analysis обрезался.
 *
 * Это НЕ порог раскладки: одна колонка начинается ниже, на `THREE_COL_MIN`, но между 600 и
 * 1000 px шапка уже обязана ужиматься. Правило живёт здесь, потому что `index.css` не умеет
 * взять константу, а дублировать число в двух местах — значит рано или поздно получить два
 * разных ответа на один вопрос.
 *
 * Дубль числа в CSS убран вместе с медиазапросом: App.tsx вешает на корень `data-narrow`,
 * и CSS спрашивает признак, а не ширину. Медиазапрос константу взять не умеет — признак умеет.
 */
export const NARROW_MAX = 600;

/* ── Вертикальный ритм оболочки ────────────────────────────────────────────────────
   Полосы оболочки (шапка, лента, рабочая область, панель вкладок, подвал) стоят вплотную,
   поэтому ритм держат не зазоры между полосами, а высоты самих полос и отступы внутри них.
   Отступы живут в шкале пробелов `--space-*` (index.css), а высоты — здесь, потому что
   нужны самому JS.

   Разделение не в удобстве, а в том, что каждая сторона знает своё. CSS не умеет взять
   константу модуля, поэтому числа, которые обязан посчитать JS, приезжают отсюда числами:
   иначе ответ на вопрос «сколько занимает полоса» жил бы в двух файлах и разошёлся бы при
   первом же изменении подвала. Обратное тоже верно — медиазапрос по ширине заставил бы CSS
   угадывать высоту подвала, и угадывать вслепую. */

export const TAP_MIN = 44;

/** Высота шапки, px: 44 px тапа плюс ряд кнопок, поэтому выше тапа. */
export const HEADER_H = 48;

/**
 * Высота панели вкладок в одноколоночном режиме, px. Замерено в браузере на 320, 360 и
 * 390 px: 44 px тапа плюс иконка с подписью, и кнопки растягиваются до высоты полосы, а
 * не растут её собой.
 */
export const TAB_BAR_H = 56;

/**
 * Поля стека тостов слева и справа, px. Стек стоит с тем же отступом от края, что и колонка
 * Клика от края окна, поэтому число одно на обе стороны и на оба режима раскладки.
 */
export const TOAST_MARGIN = 20;

/**
 * Ширина стека тостов при ширине окна `vw`: ширина колонки Клика за вычетом её же полей,
 * но никогда не шире окна за вычетом полей.
 *
 * Замороженное число здесь уже было: ширина, посчитанная для одного конкретного окна и
 * вписанная вручную, на 320 px уводила правый край карточки вместе с кнопкой закрытия за
 * экран на 46 px — прокрутки по горизонтали нет, и обрезку было не доскроллить. В
 * одноколоночном режиме колонка Клика — это всё окно, поэтому стек занимает окно за
 * вычетом полей; в трёхколоночном он живёт над колонкой Клика и берёт её ширину.
 */
export const toastStackWidth = (vw: number): number => {
  const fitWindow = vw - TOAST_MARGIN * 2;
  if (vw < THREE_COL_MIN) return Math.max(0, fitWindow);
  return Math.max(0, Math.min(clickColWidth(vw) - TOAST_MARGIN * 2, fitWindow));
};

/**
 * Отступ стека тостов от полос внизу, px — последние миллиметры воздуха, а не зазор.
 *
 * Сами высоты полос живут в CSS (`--header-h`, `--tab-bar-h`), кроме одной: высота подвала
 * зависит от того, как строка атрибуции Artificial Analysis легла на ширину окна, то есть
 * числом её не описать. Поэтому отступ подвала App.tsx меряет на лету, а это число — про
 * зазор, а не про высоту, и принадлежит оно здесь.
 */
export const TOAST_CLEARANCE = 8;

const clamp = (v: number, min: number, max: number) => Math.min(max, Math.max(min, v));

/** Ширина колонки Клика при ширине окна `vw`: те же границы, что у CSS `clamp`. */
export const clickColWidth = (vw: number): number =>
  clamp(vw * CLICK_COL_SHARE, CLICK_COL_MIN, CLICK_COL_MAX);

/** Ширина колонки магазина при ширине окна `vw`. */
export const shopColWidth = (vw: number): number =>
  clamp(vw * SHOP_COL_SHARE, SHOP_COL_MIN, SHOP_COL_MAX);
