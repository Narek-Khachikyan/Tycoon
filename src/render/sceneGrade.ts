/**
 * Художественный режим Сцены: приведение четырёх картин к одному кадру.
 *
 * Проблема, которую это решает, измерена, а не замечена глазом. Четыре Сцены рисовались
 * независимо, и в игру попали четыре разных кадра:
 *
 *   Сцена 1 — яркость 71, тепло +27   тёплый вечерний офис
 *   Сцена 2 — яркость 99, тепло −51  стеклянный полдень, холодный голубой
 *   Сцена 3 — яркость 74, тепло +15   закатный цех
 *   Сцена 4 — яркость 74, тепло −23   ночной сервер
 *
 * Вторая — выброс по обеим осям, и она же стоит в самой середине игры, на Поколениях 3 и 4:
 * игрок, дошедший до середины, выходил из тёплого тёмного мира в холодный светлый, а рамка
 * интерфейса вокруг картины переставала быть частью того же кадра.
 *
 * Замеры сняты с самой КАРТИНКИ, потому что `filter` действует ровно на неё и HUD с
 * Маскотами не множит. Итог же проверяется по композиту — там, где сходятся картинка,
 * затемнение пола и счётчики: модель обязана попадать в цель на экране, даже если считает
 * её по картинке.
 *
 * Режим не перерисовывает картины (они закоммичены как PNG и не должны требовать ассетов) и
 * не добавляет второго слоя поверх: это `filter` и один градиент. Дёшево, обратимо, и это
 * единственное место, где живёт знание «как должна выглядеть Сцена».
 */

/**
 * Сцена задаётся целевой яркостью и теплотой, а не готовым CSS-фильтром.
 *
 * Именно потому что задаются ЦЕЛИ: фильтр — это способ их достичь, и он меняется вместе
 * с браузером и с тем, как выглядит картинка. Проверяется цель, а не строка.
 */
export interface SceneGrade {
  /** Множитель яркости. */
  brightness: number;
  /** Множитель насыщенности: холодный синий Сцены 2 уходил в серость. */
  saturate: number;
  /** Доля подмешанного в тёплый тон: уводит холодные Сцены к базе интерфейса. */
  warm: number;
  /** Плотность нижнего затемнения: пол Сцены должен был выдерживать Маскоты. */
  floorShade: number;
}

/**
 * Целевой кадр.
 *
 * Яркость 73 — среднее трёх Сцен, которые и так держались вместе (71, 74, 74), то есть
 * выбором цели ничего не перекрашивается, кроме выброса. Тепло +16 — палитра интерфейса
 * тёплая (ADR-0002), и картина обязана держать ту же температуру, иначе рамка и картина
 * выглядят склеенными из двух разных материалов.
 */
const TARGET_LUMA = 73;
const TARGET_WARMTH = 16;

/**
 * Замеры исходных Сцен. Ключ — индекс Сцены, значение — пара «яркость, тепло».
 *
 * Числа измерены в браузере по композиту (средняя относительная яркость 0.2126R+0.7152G+
 * 0.0722B, тепло = R−B), см. `shot/verify-grade.mjs`. Зашиты не «на глаз»: без них режим
 * был бы набором фильтров, угаданных по превью, и следующий художник не смог бы ни понять,
 * чего от него ждут, ни проверить, что не разъехалось. Правка картинки обязана начинаться
 * с нового замера здесь, а не с правки множителей.
 */
const MEASURED: readonly [number, number][] = [
  [71.2, 27.0],
  [99.4, -51.2],
  [74.2, 15.3],
  [73.9, -22.7],
];

/**
 * Режим для Сцены: яркость к целевой, холод к целевому тону.
 *
 * Тон подмешивается `sepia`. Сколько сепии приходится на единицу теплоты — измерено: на
 * Сцене 2 доля 0.17 подняла тепло на 19 единиц, то есть около 110 единиц на единицу доли.
 * Коэффициент один на все Сцены, потому что матрица сепии — свойство фильтра, а не картинки;
 * разница между Сценами приходит из их исходной яркости и в неё укладывается.
 */
export function sceneGrade(sceneIndex: number): SceneGrade {
  const [luma, warmth] = MEASURED[clampScene(sceneIndex)] ?? MEASURED[0];
  // Холод убирается ровно настолько, насколько Сцена холоднее цели: тёплая Сцена 1 не
  // должна получать тонировку в ответ на чужой перебор.
  const warm = clamp((TARGET_WARMTH - warmth) / SEPIA_PER_WARMTH, 0, MAX_SEPIA);
  return {
    // Сепия не только желтит, но и высветляет: её матрица складывает каналы с весами, сумма
    // которых больше единицы, поэтому тон подмешивается ДО деления яркости, иначе
    // картина после правки оказывалась на 6 пунктов светлее цели.
    brightness: round4((TARGET_LUMA - SEPIA_LIFT * warm) / luma),
    // Насыщенность падает вместе с сепией: сепия сама по себе обесцвечивает, и без этого
    // холодная Сцена после тонировки стала бы розовее и ярче, то есть уехала бы дальше.
    saturate: round4(1 + 0.18 * warm),
    warm: round4(warm),
    // Светлый пол Сцены 2 требовал вдвое большего затемнения: на нём Маскоты стояли белым по
    // белому, и постоянный скрин гасил только 38% высоты.
    floorShade: round4(0.3 + 0.34 * (luma / 100)),
  };
}

/** Единиц теплоты на единицу доли сепии. Измерено на Сцене 2, см. выше. */
const SEPIA_PER_WARMTH = 110;

/**
 * Насколько сепия высветляет картинку на единицу своей доли.
 *
 * Измерено: при доле 0.42 картинка светлела примерно на 6 единиц яркости. Без этой поправки
 * режим выводил Сцену 2 ровно на ту цель, которой она достигает после тонировки, то есть
 * целевые 73 выглядели как 79.
 */
const SEPIA_LIFT = 15;

/**
 * Потолок сепии.
 *
 * 0.42 — предел, на котором Сцена 2 доходит до палитры и перестаёт быть голубой. Выше она
 * уже не стеклянный полдень, а сепия: небо уходило в охраму, и картина переставала читаться
 * как офис, ради которого её рисовали.
 */
const MAX_SEPIA = 0.42;

const clamp = (v: number, lo: number, hi: number): number => Math.min(hi, Math.max(lo, v));
/** Четыре знака: три не хватало — округление до 0.733 само по себе уводило яркость Сцены 2
 *  на 0.016 от цели, и проверка цели падала на собственном округлении. Четыре знака дают
 *  погрешность меньше 0.002 и при этом не тащат в CSS длинные хвосты. */
const round4 = (v: number): number => Math.round(v * 10000) / 10000;
const clampScene = (i: number): number => Math.min(MEASURED.length - 1, Math.max(0, Math.floor(i)));

/** CSS-фильтр Сцены. Собирается в компоненте, потому что это единственное место, где
 *  стиль доходит до DOM, — здесь живёт только решение, что за фильтр. */
export function sceneFilter(g: SceneGrade): string {
  return [
    `brightness(${g.brightness})`,
    `saturate(${g.saturate})`,
    // Тон без поворота: `sepia` сам по себе желтит, а жёлтый на тёмной базе — это ровно
    // температура палитры. `hue-rotate` уводил бы картину в розовый.
    `sepia(${g.warm})`,
  ].join(' ');
}

/** Градиент пола Сцены: сверху прозрачно, снизу затемнение под Маскотов. */
export function sceneFloorGradient(g: SceneGrade): string {
  return `linear-gradient(to top, rgba(0, 0, 0, ${g.floorShade.toFixed(2)}), transparent 42%)`;
}

/**
 * Замер Сцены и кода её кадра.
 *
 * Возвращается пара «яркость, тепло» — те же два числа, на которых считается `sceneGrade`,
 * поэтому после правки стилизации можно проверить, что цель достигнута, а не положиться на
 * глаз по превью. `ct` обязателен: картинка лежит на том же origin, что и страница, но
 * просить её с чужого нельзя.
 */
export function measureScene(img: CanvasImageSource, size = 96): Promise<{ luma: number; warmth: number }> {
  return new Promise((resolve, reject) => {
    const canvas = document.createElement('canvas');
    canvas.width = size;
    // Высота по пропорции 3:2 у art 384×256: не квадрат, потому что квадратная выборка
    // брала бы больше половины кадра из окна, и замер зависел бы от object-position.
    canvas.height = Math.round((size * 2) / 3);
    const ctx = canvas.getContext('2d', { willReadFrequently: true });
    if (!ctx) {
      reject(new Error('2d-контекст недоступен'));
      return;
    }
    ctx.drawImage(img, 0, 0, canvas.width, canvas.height);
    const data = ctx.getImageData(0, 0, canvas.width, canvas.height).data;
    let luma = 0;
    let red = 0;
    let blue = 0;
    let n = 0;
    for (let i = 0; i < data.length; i += 4) {
      luma += 0.2126 * data[i] + 0.7152 * data[i + 1] + 0.0722 * data[i + 2];
      red += data[i];
      blue += data[i + 2];
      n++;
    }
    resolve({ luma: round4(luma / n), warmth: round4((red - blue) / n) });
  });
}

/**
 * Жар поверх Сцены: тонировка и дрожащий воздух.
 *
 * Единственный слой, который двигает состояние в графике: рамка Сцены уже светится от
 * `--heat-glow`, но рамка — это 2 px по периметру, и на третьем экране её не видно. Жар
 * обязан быть виден на площади: офис краснеет и плывёт, и только тогда «перегрев» читается
 * как состояние мира, а не как число в шапке.
 *
 * Прозрачность обоих слоёв не считается здесь: её ставит CSS из того же `--heat-glow`,
 * которым уже светится рамка. Считать её в TypeScript значило бы держать третью копию
 * шкалы нагрева рядом с двумя, которые уже живут в `:root`.
 */
export function sceneHeatLayers(): { tint: string; haze: string } {
  return {
    // Тёплый снизу, как от нагревателя под полом: градиент идёт от пола вверх, потому что
    // жар поднимается, а не падает с потолка.
    //
    // Цвет намеренно алый, а не оранжевый: при `screen` на светлой Сцене оранжевый давал
    // теплоты +5.9 и жар читался только по яркости, а алый при той же прозрачности даёт
    // больше десятка. Теплота — тот канал, по которому глаз отличает жар от вспышки.
    tint: 'linear-gradient(to top, rgba(255, 92, 20, 0.55), rgba(255, 64, 16, 0.22) 44%, transparent 78%)',
    // Марево — горизонтальные полосы, а не размытие: размытие тонировки не даёт ничего,
    // потому что градиент и так нечёткий. Полосы с разной высотой и шагом не читаются как
    // узор: глаз видит дрожащий воздух, а не расчётную сетку.
    haze:
      'repeating-linear-gradient(to top, rgba(255, 168, 96, 0.2) 0 2px, transparent 2px 7px), ' +
      'linear-gradient(to top, rgba(255, 202, 148, 0.14), transparent 58%)',
  };
}
