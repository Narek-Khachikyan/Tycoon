import { GENERATIONS, type GenerationSeed, type ModelSeed } from '../data/generations';
import type { LabId } from '../data/labs';
import snapshotJson from '../data/aa-snapshot.json';

export interface AASnapshotEntry {
  name?: string;
  iq?: number;
  speed?: number;
  price?: number;
}
export type AASnapshot = Record<string, AASnapshotEntry>;

/** Модель с выведенными игровыми характеристиками (ADR-0001). */
export interface Model {
  id: string;
  name: string;
  lab: LabId;
  generation: number; // индекс Поколения, 0-based
  rank: number;
  isFlagship: boolean;
  /** Справка AA */
  iq: number;
  speed: number;
  price: number;
  fromSnapshot: boolean;
  baseCost: number;
  baseIncome: number;
  costMod: number;
}

export interface Generation {
  index: number;
  id: number;
  name: string;
  period: string;
  theme: GenerationSeed['theme'];
  scale: number;
  models: Model[];
  flagship: Model;
}

export const GEN_SCALE = 1000;

/**
 * Ступени ценовой лестницы Ранга.
 *
 * `COST_STEP` — во сколько раз дороже следующая Модель по Рангу. Подобрано измерением, а не
 * вкусом: симулятор на настоящем движке даёт флагман Поколения 0 на 9.7 минуты при 9, на
 * 21.6 при 11 и не помещает его в получасовой забег вовсе при 12. Одиннадцать — потому что
 * двенадцать Моделей Поколения 2 в этом бюджете ещё помещаются, а Поколения дальше не
 * требуют вдвое больше времени.
 */
export const COST_BASE = 15;
export const COST_STEP = 11;

/**
 * Сколько ступеней лестницы укладывается в ОДНО Поколение — всегда одинаково.
 *
 * Это и есть привязка лестницы к позиции, а не к номеру. Ранг нормируется на размер ростера
 * (см. докблок над `buildCatalog`), но пройденный путь приводится к этому фиксированному
 * числу ступеней, а не к единице. Разница принципиальна, и её видно на шаге между соседними
 * Моделями:
 *
 *   - нормировка в [0, 1]  → шаг Дохода на 19 Моделях = 12^(1/18) = 1.15;
 *   - нормировка в [0, 11] → шаг Дохода на 19 Моделях = 12^(11/18) = 4.6.
 *
 * Первый вариант тихо ломает игру: флагман Лаборатории получает ×3 от младших Агентов, а
 * парная Синергия — ещё ×1.5, и при шаге 1.15 любой из этих множителей переворачивает
 * порядок Ранга. Игрок видит, что более умная Модель приносит меньше, и решает, что Ранг
 * не значит ничего. При шаге 4.6 ни один множитель в игре (максимальный — ×3) не может
 * перевернуть лестницу, и порядок Ранга держится на любой длине ростера.
 *
 * Число 8 выбрано как наибольшее, при котором самый длинный ростер (19 Моделей) ещё даёт
 * шаг больше трёх: `INCOME_STEP^(8/18) = 3.02`. Больше — нельзя, на «Фронтире» порядок Ранга
 * переворачивался бы флагманом; меньше — можно, но тогда Поколение 0 растягивается: при
 * 11 ступенях флагман брался на 26.7 минуты и Престиж выпадал за пределы получаса.
 *
 * Проверяется тестом над каталогом с обеих сторон: шаг больше максимального множителя в
 * игре и время до Престижа в разумном бюджете.
 */
export const LADDER_SPAN = 8;

/**
 * Ступени доходной лестницы Ранга — и главное число всего баланса.
 *
 * ИНВЕРСИЯ, а не «медленный рост»: при INCOME_STEP ≤ COST_STEP доход за Токен падал с Рангом,
 * и каждая следующая Модель была строго худшей покупкой, чем первая — за Поколение 1
 * отношение Доход/цена падало в 70 раз, до флагмана доходили минуты, а игра вставала на
 * ~47 Токенов в секунду. У игрока не было цели, кроме самой дешёвой Модели.
 *
 * Теперь INCOME_STEP (12) выше COST_STEP (11): каждая следующая Модель приносит на 9% больше
 * Токенов на вложенный Токен, поэтому лестница тянет вверх. Разница маленькая намеренно: при
 * резком перевесе поздняя Модель окупалась бы мгновенно и покупка перестала бы быть выбором.
 *
 * Именно эта размена в 12/11 — из-за неё флагман Поколения N+1 строго выгоднее флагмана N по
 * Доходу на Токен, и переход в следующее Поколение не может оказаться шагом вниз. Проверяется
 * тестом над всем каталогом, а не выведено из формулы: размеры ростеров заданы руками, и
 * инвариант держится на данных, а не на арифметике.
 */
export const INCOME_BASE = 1;
export const INCOME_STEP = 12;

/**
 * Разброс цены от реальной цены $ из Artificial Analysis — ADR-0001.
 *
 * Граница ADR — ±30%, и она выдержана: `softMod` не выходит за неё, тест это проверяет.
 * Порядок цены по Рангу при этом держит не разброс, а шаг лестницы: соседние ступени
 * отличаются в `COST_STEP` раз, и на восьми Моделях это 1.38 против максимального падения
 * в 1/0.7 = 1.43 от разброса. Запас тонкий, поэтому `buildCatalog` вдобавок восстанавливает
 * порядок на соседних ступенях, если разброс всё-таки его перевернул — на длинных ростерах
 * в 12–19 Моделей шаг по доле лестницы становится меньше, и разброс в 30% уже переворачивает
 * порядок гарантированно.
 *
 * Порядок цены важен не для красоты: игрок выбирает между Моделями по смыслу («мне нужен
 * флагман»), и если магазин показывает их не по Рангу, выбор становится случайным.
 */
export const MOD_SPREAD = 0.3;

/**
 * Отношение базового Дохода первой Модели к базовой цене — «сколько Токенов в секунду
 * приносит самый дешёвый Агент за вложенные в него Токены».
 *
 * Это единственное число, которое решает, когда игра перестаёт быть кликером: пока Агент
 * приносит меньше, чем игрок успевает кликать, оптимальная стратегия — не покупать ничего и
 * кликать, и весь магазин становится декорацией. При INCOME_BASE = 0.1 первый Агент отдавал
 * 0,1/сек против 5 кликов в секунду — то есть был в 50 раз хуже клика, и переход «клики →
 * Агенты» не наступал никогда. Поднято до 1,0: Агент отдаёт 1/сек, окупается за 15 секунд
 * и перегорает клик где-то на пятом Агенте, то есть примерно через минуту игры.
 */
export const BASE_INCOME_PER_COST = INCOME_BASE / COST_BASE;

/**
 * Делитель прироста Compute в единицах масштаба Поколения.
 *
 * Живёт здесь, а не в движке: это единственное число, по которому формула Престижа совпадает
 * в самом Престиже и в Достижении «Счастливый Compute», а две копии константы разъезжаются
 * при первой же правке баланса.
 *
 * Величина решает, существует ли мета-слой вообще. Compute — единственная валюта, за которую
 * покупаются Перки, и если престиж платит щедро, то вся вторая половина игры скупается за
 * один забег и расти дальше незачем. При 1e5 первый престиж даёт около сорока единиц, чего
 * хватает на два Перка из двадцати трёх: это правильный первый вход в мета-слой, после
 * которого до остальных ещё надо дойти.
 *
 * Делитель растёт вместе с `GEN_SCALE` — те же ×1000 на Поколение, — поэтому каждое
 * Поколение требует тысячу раз больше заработка, чем предыдущее, и остаётся одинаково
 * трудным. Престиж обязан быть шагом вверх, а не бесплатным повтором забега.
 */
export const PRESTIGE_DIVISOR_UNITS = 1e5;

export const genScale = (index: number) => Math.pow(GEN_SCALE, index);

const median = (xs: number[]) => {
  const s = [...xs].sort((a, b) => a - b);
  const mid = Math.floor(s.length / 2);
  return s.length % 2 ? s[mid] : (s[mid - 1] + s[mid]) / 2;
};

/** Модификатор в пределах [1 - spread, 1 + spread], плавно растущий с отношением value/median. */
export const softMod = (value: number, med: number, sharpness = 1) =>
  1 + MOD_SPREAD * Math.tanh(sharpness * Math.log(Math.max(value, 1e-9) / Math.max(med, 1e-9)));

function mergeSeed(seed: ModelSeed, snap: AASnapshot) {
  const s = snap[seed.aa];
  const pick = (k: 'iq' | 'speed' | 'price') =>
    s && s[k] != null && !seed.pin?.includes(k) ? (s[k] as number) : seed[k];
  return { iq: pick('iq'), speed: pick('speed'), price: pick('price'), fromSnapshot: !!s };
}

export function buildCatalog(seeds: GenerationSeed[], snap: AASnapshot): Generation[] {
  return seeds.map((g, index) => {
    const scale = genScale(index);
    const merged = g.models.map((seed) => ({ seed, ...mergeSeed(seed, snap) }));
    merged.sort((a, b) => a.iq - b.iq || a.price - b.price);
    // Медиана только по положительным ценам: нулевые fallback (цена неизвестна) не должны
    // обнулять её — иначе в Поколениях 1, 2, 4 медиана 0 и softMod вырождается в 1.0/1.3,
    // а забеги до Престижа тянутся на 25–33% дольше. Ноль — это «цена неизвестна», а не
    // «бесплатно», поэтому его модификатор нейтрален (1.0): иначе отсутствие данных
    // награждалось бы скидкой 30%. Положительная цена — гладко 0.7–1.3 вокруг медианы,
    // ±30% и монотонность по Рангу держатся (порядок чинит цикл ниже).
    const positivePrices = merged.map((x) => x.price).filter((p) => p > 0);
    const medPrice = positivePrices.length > 0 ? median(positivePrices) : 1;
    // Пройденный путь в ступенях, а не в долях: см. докблок над `LADDER_SPAN`. Единичный
    // ростер из одной Модели даёт нулевые ступени, и флагман такой Модели стоит базовой цены
    // с базовым Доходом — ровно правильный ответ.
    const steps = Math.max(1, merged.length - 1);
    const models: Model[] = merged.map((x, rank) => {
      const costMod = x.price > 0 ? softMod(x.price, medPrice, 0.5) : 1;
      const span = (rank * LADDER_SPAN) / steps;
      return {
        id: x.seed.id,
        name: x.seed.name,
        lab: x.seed.lab,
        generation: index,
        rank,
        isFlagship: rank === merged.length - 1,
        iq: x.iq,
        speed: x.speed,
        price: x.price,
        fromSnapshot: x.fromSnapshot,
        costMod,
        // Показатель степени — пройденные ступени, а не rank: см. докблок над LADDER_SPAN.
        baseCost: COST_BASE * Math.pow(COST_STEP, span) * scale * costMod,
        // Доход — чистая лестница Ранга по той же доле. Скорость из AA сюда не входит: AA
        // публикует t/s для меньшинства моделей, поэтому медиана равна нулю и softMod отдавал
        // бы 1.30 тем, чью скорость измерили, и 1.00 всем остальным. Это артефакт
        // разрежённости данных, а не разница скоростей. Скорость остаётся в Модели как
        // справка AA.
        baseIncome: INCOME_BASE * Math.pow(INCOME_STEP, span) * scale,
      };
    });
    // Порядок цены по Рангу — инвариант, а не побочный эффект формулы. `costMod` (±30% от
    // реальной цены $) переворачивает соседние ступени на длинных ростерах: шаг лестницы
    // считается по доле пройденного пути, и при 19 Моделях один шаг равен 1.14 против
    // максимального падения в 1.43 от разброса. На всех восьми Поколениях это давало десять
    // таких пар, и игрок видел в магазине Модели не по Рангу.
    //
    // Восстановление локальное: поднимается только та ступень, что оказалась дешевле
    // предыдущей, ровно до неё плюс шаг. Остальные ступени и весь порядок по Рангу не
    // трогаются, а разница между соседями после правки читается как обычная ступень лестницы.
    for (let i = 1; i < models.length; i++) {
      const lower = models[i - 1].baseCost;
      if (models[i].baseCost > lower) continue;
      models[i] = { ...models[i], baseCost: lower * Math.pow(COST_STEP, LADDER_SPAN / steps) };
    }
    return {
      index,
      id: g.id,
      name: g.name,
      period: g.period,
      theme: g.theme,
      scale,
      models,
      flagship: models[models.length - 1],
    };
  });
}

/**
 * Строит каталог.
 *
 * Лестница привязана к ПОЗИЦИИ в ростере, а не к абсолютному Рангу, и это единственное
 * место, где такая привязка возможна. Размеры ростеров заданы руками и скачут с 8 до 19
 * Моделей, а формула по абсолютному Рангу давала перевёрнутый переход: цена флагмана не
 * зависит от числа Моделей (это `COST_BASE × costMod`), а Доход растёт как
 * `INCOME_STEP^rank`, то есть Поколение с длинным ростером платит за лишние ступени
 * лестницы, которых игрок не проходил. На переходах 0→1, 2→3 и 4→5 флагман нового
 * Поколения окупался ДОЛЬШЕ предыдущего — переход был шагом вниз, и это проверялось тестом
 * над всем каталогом.
 *
 * Дробный Ранг в [0, 1] — это доля пройденной лестницы, а не порядковый номер. Он
 * сохраняет ровно два свойства, ради которых лестница существует:
 *   - порядок: цена и Доход строго растут вместе с позицией (тест проверяет по каталогу);
 *   - равную окупаемость флагманов всех Поколений: у первого и последнего Ранга доля
 *     пройденного одинакова, поэтому переход перестаёт зависеть от длины ростера.
 *
 * Проверка «не меньше −3 ступени», о которой писал ADR-0004, после этого перестала быть
 * нужна: она существовала ровно для того, чтобы длина ростера не ломала переход, а
 * теперь длина на переход не влияет вовсе.
 */
export const CATALOG: Generation[] = buildCatalog(GENERATIONS, snapshotJson as AASnapshot);

export const MODEL_BY_ID: Record<string, Model> = Object.fromEntries(
  CATALOG.flatMap((g) => g.models.map((m) => [m.id, m])),
);

export const LAST_GENERATION = CATALOG.length - 1;

/** Делитель прироста Compute, приведённый к масштабу Поколения. */
export const prestigeDivisor = (generation: number): number =>
  PRESTIGE_DIVISOR_UNITS * CATALOG[generation].scale;

/**
 * Сколько Compute даёт Забег: кубический корень от заработка через делитель своего Поколения.
 *
 * Живёт здесь рядом с делителем и читается тремя местами — самим Престижем, порогом следующей
 * единицы Compute в интерфейсе и теневым Достижением «Счастливый Compute». Формула одна: три копии
 * разошлись бы при первой же правке баланса, а цикл импортов обойти нечем — модуль ничего не
 * импортирует, поэтому копия не была вынуждена.
 */
export const computeGain = (runTokens: number, generation: number): number =>
  Math.floor(Math.cbrt(runTokens / prestigeDivisor(generation)));
