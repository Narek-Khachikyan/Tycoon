/**
 * Типы языкового слоя.
 *
 * Ключом перевода служит русская строка, а не выдуманное имя: текст остаётся рядом с той
 * логикой, в которой он живёт, а полнота английского каталога проверяется компилятором —
 * строка, которой нет в `EN`, не принимается ни в `t`, ни в `msg`, ни в поле таблицы.
 */

export type Lang = 'ru' | 'en';

/** Языки, которые знает игра: порядок задаёт порядок кнопок в Настройках. */
export const LANGS: readonly Lang[] = ['ru', 'en'];

/** Известная игровая строка: ровно то, что переведено в `en`. */
export type Key = string;

/**
 * Подставляемое значение. Вложенный `Message` разворачивается сам: без этого английская
 * фраза получила бы русский кусок изнутри — например «12 {unit}» превратилась бы в
 * «12 {unit}» на английском, потому что форма числительного пришла из модуля.
 */
export type Param = string | number | Message;

export type Params = Record<string, Param>;

export interface Msg {
  readonly key: Key;
  readonly params?: Params;
}

/**
 * Что можно отдать переводчику. Строка без склейки остаётся строкой — поэтому
 * статический текст в таблицах и разметке не меняет вид, и только составленные из кусков
 * фразы заводятся через `msg`.
 */
export type Message = Key | Msg;
