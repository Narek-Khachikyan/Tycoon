/**
 * Иконки интерфейса.
 *
 * Встроенный SVG на `currentColor`, а не эмодзи из системного шрифта: эмодзи рисуются
 * по-разному в разных ОС и спорят с пиксель-артом, а игре нужен значок, одинаковый везде.
 *
 * **Одна сетка.** `viewBox` 16×16, клетка — 2 px, и все координаты и стороны в данных
 * кратны двум. Сетка 24×24, как у Маскотов, для значков не годится: в шапке их видно
 * по 16 px, и штрих в две клетки стал бы 1,3 px — `crispEdges` где-то стянул бы его в 1 px,
 * а где-то оставил 2, и значок мылился бы. Единица набора — клетка, а не пиксель.
 *
 * **Одно поле.** Рисунок живёт в квадрате 12×12 с полями по 2 px, и отступления от него
 * перечислены явно: динамик — 12×8, «Пуск» с «Паузой» — 8×10, «Далее» — 12×10,
 * «Закрыть» — 8×8. Сплошные значки вписаны в меньший квадрат намеренно: заливка на полном
 * поле весит вдвое больше контурного соседа, и «Пуск» рядом со «Справкой» читался бы вдвое
 * крупнее неё.
 *
 * **Одна детальность.** 16–20 px — реальный размер, в котором их видит игрок, поэтому
 * диагонали идут ступеньками по клетке, «Пуск» собран прямоугольниками (а не `polygon`,
 * который при `crispEdges` давал скошенное ребро), а одиночных точек и зазоров в 1 px в
 * наборе нет: на таком размере они сливаются в кашу.
 *
 * **Центровка.** Симметричные значки стоят по центру поля, то есть по линии x=8. Деталь
 * шириной в клетку по центру — свеча «i», штрих «!» — встаёт на x=7: это единственные
 * нечётные координаты в наборе, потому что смещение на 1 px внутри 16 px не видно, а
 * свеча, съехавшая на полклетки, читалась бы как кривая буква.
 *
 * **Подпись — не иконка.** Каждая иконка помечена `aria-hidden`: имя кнопки задаёт её
 * подпись, а не картинка. Иначе озвучка читала бы «график» перед «Инфо» и «кубок»
 * перед «Достижения».
 *
 * Движения в значках нет: слой 4 свеёл анимацию к словарю, а мигающий значок шумит поверх
 * той картинки, которую он должен украшать.
 */
