/** Сторона сетки рабочего места. Поверхность стола — строка 6. */
const GRID_W = 32;
const GRID_H = 16;

/**
 * Строка, на которой стоит предмет стола, — общая точка привязки для всех
 * видов мебели. Маскот встаёт на неё ногами, поэтому линия ног в ряду совпадает
 * с линией столешниц, и столы не выглядят подвешенными на разной высоте.
 *
 * Ноги Маскотов стоят вразброс от 70% (краб, кит) до 87% (капибара, вихрь) бокса,
 * а 83% — их средняя линия; здесь тот же смысл, но в единицах стола: стол
 * перекрывает ноги Маскота примерно по щиколотку, и за ним виден корпус.
 */
export const STATION_SURFACE_ROW = 6;

/** Слой прямоугольников одного тона. */
const layer = (tone: string, rects: readonly Px[] | undefined) =>
  rects && rects.length > 0 ? (
    <g fill={tone}>
      {rects.map(([x, y, w, h], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} />
      ))}
    </g>
  ) : null;

/**
 * Спрайт рабочего места для Лаборатории.
 *
 * `width` — ширина спрайта в CSS-пикселях; высота выводится из пропорции сетки,
 * потому что пропорция 32:12 и есть рисунок стола. Размер по умолчанию совпадает
 * с шириной колонки Маскотов, поэтому стол ровно занимает свою колонку.
 */
export const WorkstationSprite: React.FC<{
  lab: LabId;
  width?: number;
  className?: string;
  style?: React.CSSProperties;
}> = ({ lab, width = 64, className, style }) => {
  const art = STATION_ART[STATION_OF[lab]];
  const height = Math.round((width * GRID_H) / GRID_W);
  const p = STATION_PALETTE;

  return (
    <svg
      width={width}
      height={height}
      viewBox={`0 0 ${GRID_W} ${GRID_H}`}
      // Прямоугольники по сетке не сглаживаются: без crispEdges дробные пиксели
      // при нецелом размере размывают края, и мебель рассыпается в мыло.
      shapeRendering="crispEdges"
      // Мебель декоративная: у неё нет подписи, и её роль — объяснять, что
      // Маскот стоит за своим рабочим местом.
      aria-hidden="true"
      focusable="false"
      role="presentation"
      className={className}
      style={{ display: 'block', imageRendering: 'pixelated', flexShrink: 0, ...style }}
    >
      {layer(p.outline, art.outline)}
      {layer(p.edge, art.edge)}
      {layer(p.wood, art.wood)}
      {layer(p.body, art.body)}
      {layer(p.shade, art.shade)}
      {layer(p.metal, art.metal)}
      {layer(p.plastic, art.plastic)}
      {layer(p.glass, art.glass)}
      {layer(p.glow, art.glow)}
      {layer(p.lamp, art.lamp)}
      {layer(p.alert, art.alert)}
    </svg>
  );
};
