/**
 * Рабочие места на Сцене: у каждой нанятой Лаборатории по столу.
 *
 * До этого Сцена была пустой: Маскоты стояли на голом полу рядом с уже
 * нарисованными в живописи столами, и до первого найма офис читался как
 * недоделанный кадр. Теперь у каждого Маскота есть его собственный стол —
 * набор пиксельных примитивов, а не картинка.
 *
 * **Раскладка.** Спрайт рабочего места — 32×16 пикселей, поверхность стола на
 * строке 6. Восемь Лабораторий делят ряд_scene через `gridTemplateColumns`
 * (`auto-fit, minmax(MASCOT_COL_MIN, 1fr))`), поэтому столы физически не могут
 * наехать друг на друга: каждый лежит в своей колонке сетки, а сама колонка
 * никогда не уже стола. Строка 6 — общая у всех четырёх видов, поэтому линия
 * столешниц в ряду идёт ровно, и столы читаются как один ряд мебели, а не как
 * восемь разных предметов. Предмет на столе (монитор, стойка, лампа, ящики)
 * занимает строки 0..5 и задаёт силуэт: у Стойки он уходит в строку 0, то есть
 * выше всех, и это единственная высота в ряду.
 *
 * **Глубина.** Слой один, но он разделён по высоте: тумба со столешницей внизу
 * читается как ближний план к зрителю, а предмет на столе и Маскот за ним — как
 * средний. Стык пола и тумбы — самая тёмная линия спрайта, и именно она
 * привязывает мебель к полу Сцены, а не оставляет её висящей в воздухе.
 *
 * **Свет.** Тот же, что у Маскотов и у Золотого Токена: свет сверху-слева,
 * тень снизу-справа. Палитра мебели темнее пола Сцены, а самая светлая кромка
 * столешницы держит верхнюю границу предмета: более светлая кромка выглядела бы
 * вырезом из бумаги на живой картине.
 *
 * Ни SMIL, ни keyframes внутри SVG: анимации вешает вызывающий классом, и тогда
 * они снимаются одним правилом под `[data-motion='reduced']` вместе со всей
 * остальной анимацией игры.
 */

/** Вид рабочего места. Четыре формы на восемь Лабораторий — смотри `STATION_OF`. */
export type StationKind = 'desk' | 'rack' | 'console' | 'bench';

/**
 * Кому какое рабочее место.
 *
 * Четыре вида на восемь Лабораторий, а не восемь видов: мебель в ряду должна
 * читаться как обстановка, и восемь разных предметов на восьми местах выглядели
 * бы как витрина, а не как офис. Различаются они по назначению и по высоте
 * силуэта, а не по цвету.
 *
 * Лаборатории перебраны в порядке `LAB_IDS`, поэтому соседние места в ряду
 * всегда разного вида: у Стойки и Пульта разная высота, у Верстака справа
 * глубина вместо спинки стула.
 */
const STATION_OF: Record<LabId, StationKind> = {
  // Облачко: базовый стол с монитором — самый нейтральный вид.
  openai: 'desk',
  // Краб: стойка с юнитами выше остальных, единственная вертикаль в ряду.
  anthropic: 'rack',
  // Четырёхцвет: широкий пульт с лампой — единственный тёплый источник света.
  google: 'console',
  // Сфера: верстак с ящиками, единственный, у которого справа глубина.
  xai: 'bench',
  // Китик, Плюш, Ветерок, Капибара: по кругу, чтобы ряд не состоял из пар.
  deepseek: 'desk',
  meta: 'rack',
  mistral: 'console',
  alibaba: 'bench',
};

/**
 * Какая Лаборатория получит сколько рабочих мест по порядку. Не нужно: по одному
 * на Лабораторию, а порядок лабораторий в ряду и так задаётся `LAB_IDS`.
 */

/** Пиксель карты: x, y, ширина, высота. */
type Px = readonly [number, number, number, number];

interface StationArt {
  readonly outline: readonly Px[];
  /** Светлая кромка столешницы — верхняя граница предмета. */
  readonly edge: readonly Px[];
  /** Дерево, светлый тон. */
  readonly wood: readonly Px[];
  /** Дерево, база. */
  readonly body: readonly Px[];
  /** Дерево, тень: ящики, ниша тумбы. */
  readonly shade: readonly Px[];
  /** Тёмный металл корпуса прибора. */
  readonly metal?: readonly Px[];
  /** Пластик корпуса прибора. */
  readonly plastic?: readonly Px[];
  /** Стекло экрана. */
  readonly glass?: readonly Px[];
  /** Свечение экрана. */
  readonly glow?: readonly Px[];
  /** Тёплый свет лампы. */
  readonly lamp?: readonly Px[];
  /** Красный индикатор. */
  readonly alert?: readonly Px[];
}

