// ── Дрон ──────────────────────────────────────────────────────────────────────
//
// Сплющенная 40×16 картинка: size означает ширину, и высоту приходится выводить из
// пропорции viewBox. В квадрате SVG отцентрировал бы дрон и оставил пустой бокс сверху и
// снизу, а с ним лишний размер в раскладке и область клика больше самой картинки.
//
// Светлый серый — тот же, что у приборного Маскота Сферы: дрон это тоже прибор, и
// холодный металл здесь уместен, тогда как синеватая шкала из шести ступеней читалась
// как отдельная техника рядом с тёплым офисом. Нос справа: дрон летит туда, куда его
// выносит пролёт.

