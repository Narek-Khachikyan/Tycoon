const POP_LIGHT: readonly Px[] = [[11, 4, 2, 1], [4, 9, 2, 1]];
const POP_SHADE: readonly Px[] = [[19, 11, 2, 1], [17, 18, 1, 1]];
const POP_DARK: readonly Px[] = [[6, 19, 1, 1]];
const POP_WHITE: readonly Px[] = [[11, 10, 3, 3]];
const POP_ACCENT: readonly Px[] = [[12, 8, 1, 1], [9, 11, 1, 1], [14, 11, 1, 1], [12, 15, 1, 1]];

