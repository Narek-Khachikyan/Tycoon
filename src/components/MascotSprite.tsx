/** Сторона сетки: 24 пикселя, как логика прежних растровых Маскотов. */
const GRID = 24;

/** Один слой прямоугольников. Ключ — тон из палитры Маскота. */
const layer = (tone: string, rects: readonly Px[] | undefined) =>
  rects && rects.length > 0 ? (
    <g fill={tone}>
      {rects.map(([x, y, w, h], i) => (
        <rect key={i} x={x} y={y} width={w} height={h} />
      ))}
    </g>
  ) : null;

export const MascotSprite: React.FC<MascotProps> = ({
  lab,
  size = 32,
  animated = false,
  className = '',
}) => {
  const animClass = animated ? 'animate-mascot-bob' : '';
  const art = MASCOT_ART[lab];
  const palette = MASCOT_PALETTE[lab];

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${GRID} ${GRID}`}
      // Прямоугольники по сетке не сглаживаются: без crispEdges браузер
      // размывает края по дробным пикселям, и пиксель-арт рассыпается в мыло
      // ровно на нецелом размере — то есть на любом, кроме 24 и 48.
      shapeRendering="crispEdges"
      className={`${animClass} ${className}`.trim()}
      // Маскот всегда стоит рядом с названием Лаборатории, поэтому картинка
      // декоративная: без aria-hidden озвучка читала бы «изображение» перед именем.
      aria-hidden="true"
      focusable="false"
      role="presentation"
      style={{ display: 'block', imageRendering: 'pixelated', flexShrink: 0 }}
    >
      {layer(palette.outline, art.outline)}
      {layer(palette.body, art.body)}
      {layer(palette.light, art.light)}
      {layer(palette.shade, art.shade)}
      {layer(palette.white, art.white)}
      {layer(palette.dark, art.dark)}
      {layer(palette.accent, art.accent)}
    </svg>
  );
};

