/**
 * Маскоты Лабораторий — пиксель-арт, встроенный в код прямоугольниками на сетке 24×24.
 *
 * Раньше это были растровые PNG в `public/sprites`: логика 24×24, экспорт 96×96
 * nearest-neighbour. Растр выглядел ровно на одной платформе и в одном размере,
 * а перерисовать его в репозитории было нечем — исходники лежат в
 * `public/sprites/raw`, который вне git (AGENTS.md), и команда `npm run sprites`
 * указывает на отсутствующий `scripts/chroma-key.py`. Встроенный SVG решает и то
 * и другое: Маскот тянется на любой размер из того же описания, и правится он
 * в этом файле.
 *
 * **Почему Маскоты нарисованы, а не отмазаны по палитре.** Растровые Маскоты
 * различались в основном цветом: силуэт у шести из восьми был одним и тем же
 * скруглённым прямоугольником, а отличались клешни у краба, хвост у кита,
 * кольцо у сферы и ушки у плюша — то есть деталь была, а читаемого силуэта не
 * было, и на Сцене рядом из восьми фигур выходили восемь одинаковых пятен.
 * Теперь различие держит силуэт: облако с ногами, краб с клешнями и четырьмя
 * ногами, квадрат из четырёх секторов, сфера с кольцом, кит с хвостом, плюш с
 * ушами, завиток с полосами ветра, капибара с широкой мордой.
 *
 * **Общие правила рисования, чтобы восемь картинок читались как один ряд.**
 *
 * - Сетка 24×24, один пиксель — один `<rect>`. `shapeRendering: crispEdges`
 *   вместо сглаживания, как у `Icon` и спрайтов событий.
 * - Обводка `#171310` ровно в один пиксель по всему силуэту: у растра обводки
 *   не было вовсе, и светлый Плюш или Сфера на почти чёрном поле Сцены 4
 *   теряли край.
 * - Свет сверху-слева, тень снизу-справа. Тот же свет, что у Золотого Токена в
 *   `EventSprites`: падающий свет сцены идёт из окна слева, и обратная
 *   подсветка спорила бы с ним.
 * - Три тона тела: свет `#…`, база `#…`, тень `#…`. Переходы ступенчатые, без
 *   промежуточных оттенков: в пиксель-арте рампа не бывает.
 * - Глаза у всех — белый прямоугольник с тёмным зрачком, кроме Сферы: у неё
 *   визорная щель, потому что это прибор, а не лицо. У Завитка глаза
 *   прищурены, у Капибары посажены высоко и мелко — это характер, а не деталь.
 *
 * Порядок прямоугольников в каждом слое значим: тело кладётся на обводку, тень
 * на тело, глаза на тень, и только так силуэт остаётся сплошным.
 */

/** Пиксель карты: x, y, ширина, высота. */
type Px = readonly [number, number, number, number];

interface MascotArt {
  /** Обводка силуэта. Кладется первой: всё остальное ложится поверх. */
  readonly outline: readonly Px[];
  /** База тела. */
  readonly body: readonly Px[];
  /** Свет сверху-слева. */
  readonly light: readonly Px[];
  /** Тень снизу-справа. */
  readonly shade: readonly Px[];
  /** Белый: глаза, брюхо, морда. */
  readonly white?: readonly Px[];
  /** Тёмная деталь: зрачки, рот, визор. */
  readonly dark: readonly Px[];
  /** Акцентная деталь: румянец, свечение визора, капли фонтана. */
  readonly accent?: readonly Px[];
}

