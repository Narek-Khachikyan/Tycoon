/**
 * Сигналы интерфейса и редких событий.
 *
 * Отдельный модуль от `sound.ts` не по количеству функций, а по общему долгу: щелчок
 * переключателя и тик наведения повторяются сотни раз за забег, и звук, который однажды
 * стал раздражать, портит игру целиком — а та же арифметика звука в `sound.ts` работает с
 * одноразовыми сигналами, где усталость тембра не стоит ничего.
 *
 * Отсюда три обязательных свойства каждого голоса: громкость, при которой десять
 * одновременных сигналов не упираются в перегруз, ровный старт огибающей с нуля, и
 * маленький разброс высоты на каждый вызов. Правила не разбросаны по функциям, а
 * собраны в помощниках `blip` и `wobble` — иначе каждое из них пришлось бы помнить всем.
 *
 * Контекст и мастер-шина не наши: ими владеет `sound.ts`, и громкость игрока применяет он.
 */

import { effectBus, runningBus, type AudioBus, type SoundSettings } from './sound';

/**
 * Потолок суммы голосов одного звукового сигнала.
 *
 * Мастер-шина только масштабирует сумму, поэтому единственная защита от перегруза —
 * арифметика пиков: десять одновременных сигналов не должны перевалить 1.0.
 * Потолок ставится на сумму голосов одного сигнала, а не на голос: одновременные голоса
 * складываются, и потолок «на голос» ничего бы не ограничил.
 *
 * Число не приватное: на него опирается музыка, которая обязана звучать ПОД эффектами, и
 * держать две копии одного потолка в двух модулях значило бы забыть обновить одну из них.
 */
export const SFX_PEAK_CEILING = 0.14;

/**
 * Расстройка пары голосов, центы.
 *
 * Шесть центов — это порог, ниже которого ухо слышит «плавающую ноту», а не «два голоса»:
 * ниже трёх центров расстройка читается как брак, выше десяти — как расстроенный
 * инструмент. Ровно на этом значении пара превращается в хор.
 */
const SHIMMER = 6;

/**
 * Хвост после конца огибающей.
 *
 * Осциллятор должен перестать звучать после тишины, а не в момент её достижения: обрыв
 * ровно в 0.001 всё равно слышен как щелчок на тихих сигналах.
 */
const STOP_TAIL = 0.005;

/**
 * Разброс высоты на каждый вызов.
 *
 * Без него к десятому Клику ухо выучивает тембровую оболочку и начинает слышать синтезатор,
 * а не игру. Два-три процента держатся на грани заметности: несовпадение ещё не читается как
 * «расстроено», но повтор уже не узнаётся как копия.
 *
 * Диапазон узкий намеренно. Случайность, которую слышно, игрок списывает на лаги, а
 * случайность, которую не слышно, не спасает от усталости тембра.
 */
function wobble(freq: number, span = 0.03): number {
  return freq * (1 + (Math.random() * 2 - 1) * span);
}

/** Голос без свипа: нота, которая звучит, пока гаснет. */
interface VoiceBase {
  /**
   * Форма волны. Четыре типа покрывают весь набор: квадрат резкий, треугольник мягкий,
   * синус стеклянный, пила горит. Одного типа на все сигналы не хватило бы — сигналы
   * начали бы сливаться в один тембр, и различать их пришлось бы по высоте.
   */
  waveform: OscillatorType;
  /** Частота в герцах. Всегда уже разбросана: `wobble` здесь, а не у вызывающего кода. */
  freq: number;
  /**
   * Пик голоса.
   *
   * Сумма голосов одного сигнала держится под `SFX_PEAK_CEILING`.
   */
  peak: number;
  /** Разгон с нуля, с. */
  attack: number;
  /** Спад от пика до тишины, с. */
  decay: number;
  /** Сдвиг начала от текущего момента контекста, с. */
  at?: number;
  /** Расстройка в центах: пара голосов в ±`SHIMMER` звучит как хор, а не как один тон. */
  detune?: number;
}

/**
 * Голос со свипом — отдельная ветка, а не флаг у `VoiceBase`.
 *
 * Частота-цель без времени свипа или время без цели — состояния, которых не бывает: оба
 * случая означали бы, что автор перепутал ноту с движением, и звучали бы одинаково.
 */
type Voice =
  | (VoiceBase & { glide?: undefined; glideTime?: undefined })
  | (VoiceBase & { glide: number; glideTime: number });

/**
 * Один голос: осциллятор, огибающая, выход в назначение.
 *
 * Огибающая обязана начинаться строго с нуля и разгоняться 2–5 мс. Присваивание `.value`
 * на живом AudioParam начинает сигнал с ненулевого значения, и на тихих сигналах — а тик
 * наведения это 0.03 — щелчок перед нотой слышно лучше, чем саму ноту.
 *
 * Голос всегда умирает в тишину до `stop()`: без этого ухо ловит обрыв на хвосте, а у
 * `playMilestoneSound` хвост длинный, и обрыв слышался бы как щелчок в конце события.
 */
function blip({ ctx, master }: AudioBus, v: Voice): void {
  const t0 = ctx.currentTime + (v.at ?? 0);
  const end = t0 + v.attack + v.decay;

  const osc = ctx.createOscillator();
  const gain = ctx.createGain();

  osc.type = v.waveform;
  osc.frequency.setValueAtTime(v.freq, t0);
  if (v.glide !== undefined) osc.frequency.exponentialRampToValueAtTime(v.glide, t0 + v.glideTime);
  if (v.detune !== undefined) osc.detune.setValueAtTime(v.detune, t0);

  gain.gain.setValueAtTime(0, t0);
  gain.gain.linearRampToValueAtTime(v.peak, t0 + v.attack);
  gain.gain.exponentialRampToValueAtTime(0.001, end);

  osc.connect(gain).connect(master);

  osc.start(t0);
  osc.stop(end + STOP_TAIL);
}

/**
 * Переключатель: сегментированный контрол, режим «покупать/продавать».
 *
 * Ровная короткая нота средней высоты и больше ничего: переключатель щёлкает сотни раз за
 * сессию, и любой хвост или свип превращается в раздражающий призвук. Частота не уходит
 * вверх — это отличие от Клика на той же высоте: два соседних действия обязаны звучать
 * по-разному даже вперемешку, а ползущий вверх сигнал читался бы как «ещё».
 */
export function playToggleSound(settings: SoundSettings): void {
  const bus = effectBus(settings);
  if (!bus) return;

  blip(bus, { waveform: 'square', freq: wobble(620, 0.02), peak: 0.0435, attack: 0.002, decay: 0.06 });
}

/**
 * Веха: главный такт прогрессии, и звук обязан быть событием.
 *
 * Отличие от Достижения не в длительности, а в согласии: Достижение — минорное квадратное
 * арпеджио, Веха — мажорное треугольное, и слух узнаёт их в разных точках одной секунды.
 * Трезвучие F5–A5–C6 разложено на три восходящие ноты, чтобы аккорд разворачивался, а не
 * звучал готовым: главный такт прогрессии обязан занять внимание, а не отнять его.
 *
 * Нижняя пара F4 в расстрое — «тёплое» тело аккорда, и заодно хор: одна нота на такой
 * высоте звучит как калибровочный тон тестера, две расстроенные — как голос.
 *
 * Задержка в 55 мс есть только между нотами трезвучия: первая нота стартует в текущий
 * момент контекста, и любая задержка первого голоса ощущалась бы как лаг.
 */
export function playMilestoneSound(settings: SoundSettings): void {
  const bus = runningBus(settings);
  if (!bus) return;

  // Тело аккорда: F4 в хоре. Держит звук дольше, чем верхнее трезвучие.
  blip(bus, { waveform: 'triangle', freq: wobble(349.23), peak: 0.0135, attack: 0.004, decay: 1.3, detune: -SHIMMER });
  blip(bus, { waveform: 'triangle', freq: wobble(349.23), peak: 0.0135, attack: 0.004, decay: 1.3, detune: SHIMMER });
  // Мажорное треугольное трезвучие, разложенное на восходящие ноты.
  blip(bus, { waveform: 'triangle', freq: wobble(698.46), peak: 0.0121, attack: 0.004, decay: 0.85 });
  blip(bus, { waveform: 'triangle', freq: wobble(880), peak: 0.0121, attack: 0.004, decay: 0.85, at: 0.055 });
  blip(bus, { waveform: 'triangle', freq: wobble(1046.5), peak: 0.0121, attack: 0.004, decay: 0.95, at: 0.11 });
}

/**
 * Щелчок перед Престижем — предохранитель, а не праздник.
 *
 * `playPrestigeSound` остаётся торжеством, и подтверждать его тем же звуком было бы
 * растратой: игрок слышал бы тост дважды и перестал бы слышать сам Престиж. Поэтому здесь
 * короткое падение вниз с тонким верхним тиком — «щёлкнуло и защёлкнулось».
 *
 * Тело взято ниже всех остальных сигналов модуля: кнопка, которая стирает Забег, должна
 * отличаться на слух даже в соседстве с подтверждением окна.
 */
export function playPrestigeConfirmSound(settings: SoundSettings): void {
  const bus = effectBus(settings);
  if (!bus) return;

  // G3 → D3 за 60 мс: короткий «клац», а не нота.
  const body = wobble(196, 0.02);
  blip(bus, {
    waveform: 'triangle',
    freq: body,
    glide: body * (146.83 / 196),
    glideTime: 0.06,
    peak: 0.0411,
    attack: 0.002,
    decay: 0.09,
  });
  // Верхний тик — та самая защёлка, ради которой этот сигнал и существует.
  blip(bus, { waveform: 'sine', freq: wobble(880, 0.02), peak: 0.0242, attack: 0.002, decay: 0.03 });
}

/**
 * Compute-кристалл: звон подбора.
 *
 * «Блеск» делает не высота, а негармоничный частичный: точно кратные гармоники звучат как
 * электронный пик, а слегка «неправильный» верхний обертон — как стекло. Отношение 2.76
 * взято у колокола: ровная квинта слышалась бы как шаблон, а 2.76 — как настоящий
 * гранулят.
 *
 * Хвост короткий намеренно: кристалл подбирают часто, и длинное кольцо превратило бы сорок
 * пингов в арпеджио. Расстроенная пара в основе — тот же хор, что у Вехи, только выше и
 * короче: блеск должен различаться с игровым сигналом, а не сливаться с ним.
 */
export function playCrystalSound(settings: SoundSettings): void {
  const bus = runningBus(settings);
  if (!bus) return;

  // Сумма пиков здесь ниже, чем у Вехи или подтверждения Престижа, и это единственный сигнал
  // модуля, который реально накладывается сам на себя: кристаллы зреют очередью, и игрок
  // подбирает их пачками. Блеск здесь держит не громкость, а расстроенная пара и частичный —
  // поднимать пики было бы попыткой вынести «блеск» в амплитуду вместо тембра.
  const base = wobble(2093);
  for (const cents of [-SHIMMER, SHIMMER]) {
    blip(bus, { waveform: 'sine', freq: base, peak: 0.0155, attack: 0.002, decay: 0.16, detune: cents });
  }
  blip(bus, { waveform: 'sine', freq: base * 2.76, peak: 0.0126, attack: 0.002, decay: 0.07 });
}
